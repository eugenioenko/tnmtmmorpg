import {
  definePlugin,
  DUNGEON_ENTRY,
  DUNGEON_SIZE,
  dungeonWorldId,
  isDungeonWorldId,
  OVERWORLD,
  WORLD_CENTER_X,
  WORLD_CENTER_Y,
  type EntityState,
  type ItemDef,
  type WorldAPI,
} from '@game/shared';

/**
 * Caves: instanced dungeons behind entrances scattered across the
 * overworld. Stepping in puts you (and anyone who follows within half a
 * minute, or any time if they share your party) in your own copy of the cave: a chain of chambers full of
 * monsters, ending in a guardian. Felling the guardian opens its hoard,
 * which each player who made it can loot once per run.
 *
 * The rock comes from core's 'caves' generator (world id
 * 'dungeon:<x>,<y>/<copy>'); monsters come from the bestiary through its
 * 'bestiary:spawn' event; rewards go out through 'character:grant' and
 * world.give. Copies are reused once they have stood empty for a minute.
 */

export interface CaveComponent {
  name: string;
  level: number;
}

export interface DungeonStatus {
  cave: string;
  level: number;
  guardian: string;
  cleared: boolean;
  copy: number;
  looted: boolean;
  /** Torches line this cave's walls; the rest are dark but for crystals. */
  lit: boolean;
}

interface Instance {
  id: string;
  caveId: number;
  ex: number;
  ey: number;
  name: string;
  level: number;
  copy: number;
  created: number;
  members: Set<number>;
  guardian: string;
  bossId?: number;
  cleared: boolean;
  looted: Set<number>;
  emptySince: number | null;
  own: number[];
  /**
   * Readying is spread over ticks to stay inside the system time budget. It
   * waits a couple of ticks after the first arrival, so the rock is
   * generated by core (for that player's snapshot) rather than in here.
   */
  stage: 'wait' | 'survey' | 'clear' | 'populate' | 'ready';
  survey?: Survey;
}

const COPIES = 16;
const JOIN_WINDOW = 300;
const EMPTY_TICKS = 600;
const SAFE_RADIUS = 30;
const CAVE_CHANCE = 0.2;
const FIRST_CAVE = { dx: 6, dy: -40 };
const CHEST_SHUT = 'objects/frames/86cb94';
const CAVE_MOUTH = { frame: 'objects/portal-base', scale: 1.7, tint: 0x3b3129 };
const CHEST_OPEN = 'objects/frames/86cba0';

const CAVE_NAMES = [
  'Wolfden Grotto', 'Mossmouth Cave', 'Hollowdeep', 'The Gnawing Dark', 'Bramblehole',
  'Shiverstone Caverns', 'Old Delver’s Pit', 'Echoing Hollow', 'The Sunken Den', 'Ratscrabble Warren',
  'Grimwater Cave', 'The Long Throat', 'Lanternless Hole', 'Thornroot Cavern', 'Bonepile Grotto',
];
const GUARDIANS = [
  ['Gravemaw', 'Cave Tyrant'], ['Old Snarl', 'Den Mother'], ['Hollowfang', 'Warden of the Deep'],
  ['Mirefoot', 'Lurker Below'], ['The Pale Thing', 'Eater of Lanterns'], ['Ironhide', 'Guardian of the Hoard'],
  ['Whisperjaw', 'Lord of Echoes'], ['Grubmother', 'Queen of the Warren'],
] as const;

export const ITEMS: ItemDef[] = [
  { id: 'dungeons:guardian_trophy', name: 'Guardian’s Trophy', tags: ['loot', 'treasure'], stack: 10, value: 45, icon: '🏆', description: 'Proof you went all the way down. Traders pay well for these.' },
  { id: 'dungeons:cave_crystal', name: 'Cave Crystal', tags: ['loot', 'treasure', 'material'], stack: 20, value: 18, icon: '💎', description: 'Grown in the dark over a thousand years.' },
];

let clock = 0;
const instances = new Map<string, Instance>();

const floor = (n: number): number => n | 0;
const cheb = (a: { x: number; y: number }, b: { x: number; y: number }): number => {
  const dx = a.x > b.x ? a.x - b.x : b.x - a.x;
  const dy = a.y > b.y ? a.y - b.y : b.y - a.y;
  return dx > dy ? dx : dy;
};

function hash(x: number, y: number): number {
  let h = (x * 374761393 + y * 668265263) | 0;
  h = ((h ^ (h >>> 13)) * 1274126177) | 0;
  return (h ^ (h >>> 16)) >>> 0;
}

/** Deeper caves further from the village, one step tougher than the ground outside. */
function levelAt(x: number, y: number): number {
  const d = cheb({ x, y }, { x: WORLD_CENTER_X, y: WORLD_CENTER_Y });
  const level = 2 + floor((d - 24) / 16);
  return level < 2 ? 2 : level > 30 ? 30 : level;
}

function caveOf(e: EntityState | undefined): CaveComponent | undefined {
  const c = e?.components['dungeons:cave'] as CaveComponent | undefined;
  return c && typeof c.name === 'string' && typeof c.level === 'number' ? c : undefined;
}

function spawnEntrance(world: WorldAPI, x: number, y: number): number {
  const h = hash(x, y);
  const name = CAVE_NAMES[h % CAVE_NAMES.length];
  const level = levelAt(x, y);
  return world.spawn('dungeons:entrance', { x, y }, {
    'dungeons:cave': { name, level } satisfies CaveComponent,
    label: `${name} · Lv ${level}`,
    appearance: CAVE_MOUTH,
  });
}

function playersIn(world: WorldAPI, worldId: string): EntityState[] {
  return world
    .queryNear(DUNGEON_SIZE >> 1, DUNGEON_SIZE >> 1, DUNGEON_SIZE, worldId)
    .filter((e) => e.kind === 'player');
}

function say(world: WorldAPI, id: number, text: string, tone = 'quest'): void {
  world.emit('character:grant', { entityId: id, reason: text, tone });
}

interface Spot {
  x: number;
  y: number;
  d: number;
}

/** Every copy of a cave shares its rock, so each layout is surveyed once. */
interface Layout {
  tiles: Spot[];
  deepest: Spot;
}

const layouts = new Map<string, Layout>();
const SURVEY_STEP = 300;

/** A breadth-first walk of the cave floor from the entry tile, a slice per tick. */
interface Survey {
  dist: Map<number, number>;
  queue: number[];
  head: number;
}

const cell = (x: number, y: number): number => y * DUNGEON_SIZE + x;

function startSurvey(): Survey {
  const start = cell(DUNGEON_ENTRY.x, DUNGEON_ENTRY.y);
  return { dist: new Map([[start, 0]]), queue: [start], head: 0 };
}

/** Returns the finished layout, or undefined while there is floor left to walk. */
function stepSurvey(world: WorldAPI, worldId: string, s: Survey): Layout | undefined {
  const stop = s.head + SURVEY_STEP;
  while (s.head < s.queue.length && s.head < stop) {
    const at = s.queue[s.head++];
    const x = at % DUNGEON_SIZE;
    const y = floor(at / DUNGEON_SIZE);
    const d = (s.dist.get(at) ?? 0) + 1;
    for (const [nx, ny] of [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]]) {
      if (nx < 0 || ny < 0 || nx >= DUNGEON_SIZE || ny >= DUNGEON_SIZE) continue;
      const k = cell(nx, ny);
      if (s.dist.has(k) || !world.walkable(nx, ny, worldId)) continue;
      s.dist.set(k, d);
      s.queue.push(k);
    }
  }
  if (s.head < s.queue.length) return undefined;
  const tiles = [...s.dist.entries()].map(([k, d]) => ({ x: k % DUNGEON_SIZE, y: floor(k / DUNGEON_SIZE), d }));
  return { tiles, deepest: tiles.reduce((a, b) => (b.d > a.d ? b : a), tiles[0]) };
}

/** Anything left behind by the copy's previous group goes. */
function clear(world: WorldAPI, inst: Instance): void {
  for (const e of world.queryNear(DUNGEON_SIZE >> 1, DUNGEON_SIZE >> 1, DUNGEON_SIZE, inst.id)) {
    if (e.kind !== 'player') world.despawn(e.id);
  }
}

/** An exit, the guardian and its hoard, and the cave's other residents. */
function populate(world: WorldAPI, inst: Instance, layout: Layout): void {
  const { tiles, deepest } = layout;
  inst.own.push(
    world.spawn('dungeons:exit', { x: DUNGEON_ENTRY.x - 2, y: DUNGEON_ENTRY.y }, { label: 'Way out' }, inst.id),
  );

  const chestSpot =
    tiles.find((t) => cheb(t, deepest) === 2 && t.d >= deepest.d - 3) ??
    tiles.find((t) => cheb(t, deepest) === 1) ??
    deepest;
  inst.own.push(
    world.spawn(
      'dungeons:chest',
      { x: chestSpot.x, y: chestSpot.y },
      {
        label: 'Guardian’s hoard (sealed)',
        'dungeons:hoard': { open: false },
        appearance: { frame: CHEST_SHUT, scale: 1.6 },
      },
      inst.id,
    ),
  );

  const [bossName, bossTitle] = guardianOf(inst.ex, inst.ey);
  world.emit('bestiary:spawn', {
    world: inst.id,
    x: deepest.x,
    y: deepest.y,
    level: inst.level + 1,
    boss: { name: bossName, title: bossTitle },
    then: (_w: WorldAPI, id: number) => {
      inst.bossId = id;
    },
  });

  const picked: Spot[] = [];
  const candidates = tiles.filter((t) => t.d >= 10 && cheb(t, deepest) > 6);
  for (let attempt = 0; attempt < 200 && picked.length < 12; attempt++) {
    const t = candidates[floor(world.rng() * candidates.length)];
    if (!t || picked.some((p) => cheb(p, t) < 5)) continue;
    picked.push(t);
  }
  for (const spot of picked) {
    const pack = world.rng() < 0.35 ? 2 : 1;
    for (let i = 0; i < pack; i++) {
      const x = spot.x + i;
      if (i > 0 && !tiles.some((t) => t.x === x && t.y === spot.y)) continue;
      world.emit('bestiary:spawn', {
        world: inst.id,
        x,
        y: spot.y,
        level: inst.level + (world.rng() < 0.2 ? 1 : 0),
      });
    }
  }
}

/** One step of readying a copy; at most one per tick across all copies. */
function prepare(world: WorldAPI, inst: Instance): void {
  const key = `${inst.ex},${inst.ey}`;
  switch (inst.stage) {
    case 'wait':
      if (clock - inst.created < 2) return;
      if (!layouts.has(key)) inst.survey = startSurvey();
      inst.stage = layouts.has(key) ? 'clear' : 'survey';
      return;
    case 'survey': {
      const done = inst.survey ? stepSurvey(world, inst.id, inst.survey) : undefined;
      if (!done) return;
      layouts.set(key, done);
      inst.survey = undefined;
      inst.stage = 'clear';
      return;
    }
    case 'clear':
      clear(world, inst);
      inst.stage = 'populate';
      return;
    case 'populate': {
      const layout = layouts.get(key);
      if (layout) {
        populate(world, inst, layout);
        illuminate(world, inst, layout);
      }
      inst.stage = 'ready';
      return;
    }
  }
}

/** Roughly two caves in five have someone keeping the torches burning. */
function isLit(x: number, y: number): boolean {
  return hash(x + 17, y - 31) % 5 < 2;
}

/** Wall torches along the passages of a lit cave, and glowing crystals in every cave. */
function illuminate(world: WorldAPI, inst: Instance, layout: Layout): void {
  const floorAt = new Set(layout.tiles.map((t) => cell(t.x, t.y)));
  const byWall = layout.tiles.filter(
    (t) => !floorAt.has(cell(t.x, t.y - 1)) && floorAt.has(cell(t.x, t.y + 1)),
  );
  const placed: Spot[] = [];
  const place = (pool: Spot[], spacing: number, max: number, make: (t: Spot) => void): void => {
    for (let attempt = 0; attempt < 400 && max > 0; attempt++) {
      const t = pool[floor(world.rng() * pool.length)];
      if (!t || placed.some((p) => cheb(p, t) < spacing)) continue;
      placed.push(t);
      make(t);
      max--;
    }
  };
  if (isLit(inst.ex, inst.ey)) {
    place(byWall, 6, 40, (t) => {
      inst.own.push(
        world.spawn(
          'dungeons:sconce',
          { x: t.x, y: t.y },
          { appearance: { emoji: '🔥', scale: 0.55 }, light: { radius: 4.5, flicker: 0.6 } },
          inst.id,
        ),
      );
    });
  }
  const deep = layout.tiles.filter((t) => t.d >= 8);
  place(deep, 9, 10, (t) => {
    const hue = CRYSTAL_HUES[floor(world.rng() * CRYSTAL_HUES.length)];
    inst.own.push(
      world.spawn(
        'dungeons:crystal',
        { x: t.x, y: t.y },
        { appearance: { emoji: '💎', scale: 0.7 }, light: { radius: 2.6, color: hue, intensity: 0.7 } },
        inst.id,
      ),
    );
  });
}

const CRYSTAL_HUES = [0x6fd8ff, 0xb48cff, 0x7dffc4];

function guardianOf(x: number, y: number): readonly [string, string] {
  return GUARDIANS[hash(x, y) % GUARDIANS.length];
}

/** The party feature's public tag, if it is installed and the player is in one. */
function partyIdOf(e: EntityState | undefined): number | undefined {
  const tag = e?.components['party:tag'] as { id?: unknown } | undefined;
  return typeof tag?.id === 'number' ? tag.id : undefined;
}

function freeCopy(caveX: number, caveY: number): number | undefined {
  for (let copy = 0; copy < COPIES; copy++) {
    if (!instances.has(dungeonWorldId(caveX, caveY, copy))) return copy;
  }
  return undefined;
}

function status(inst: Instance, playerId: number): DungeonStatus {
  return {
    cave: inst.name,
    level: inst.level,
    guardian: inst.guardian,
    cleared: inst.cleared,
    copy: inst.copy + 1,
    looted: inst.looted.has(playerId),
    lit: isLit(inst.ex, inst.ey),
  };
}

function refresh(world: WorldAPI, inst: Instance): void {
  for (const p of playersIn(world, inst.id)) world.update(p.id, { 'dungeons:status': status(inst, p.id) });
}

function enter(world: WorldAPI, playerId: number, args: unknown): void {
  const targetId = (args as { targetId?: unknown } | undefined)?.targetId;
  const me = world.get(playerId);
  const cave = typeof targetId === 'number' ? world.get(targetId) : undefined;
  const info = caveOf(cave);
  if (!me || !cave || !info || cave.kind !== 'dungeons:entrance') return;
  if ((me.world ?? OVERWORLD) !== (cave.world ?? OVERWORLD) || cheb(me, cave) > 2) return;

  const mine = [...instances.values()].filter((i) => i.caveId === cave.id);
  const party = partyIdOf(me);
  let inst =
    mine.find((i) => i.members.has(playerId)) ??
    (party === undefined
      ? undefined
      : mine.find((i) => [...i.members].some((id) => partyIdOf(world.get(id)) === party))) ??
    mine.find((i) => !i.cleared && clock - i.created <= JOIN_WINDOW);
  if (!inst) {
    const copy = freeCopy(cave.x, cave.y);
    if (copy === undefined) {
      say(world, playerId, `${info.name} is crowded right now. Try again shortly.`, 'bad');
      return;
    }
    inst = {
      id: dungeonWorldId(cave.x, cave.y, copy),
      caveId: cave.id,
      ex: cave.x,
      ey: cave.y,
      name: info.name,
      level: info.level,
      copy,
      created: clock,
      members: new Set(),
      guardian: guardianOf(cave.x, cave.y)[0],
      cleared: false,
      looted: new Set(),
      emptySince: null,
      own: [],
      stage: 'wait',
    };
    instances.set(inst.id, inst);
    world.log(`opened ${inst.id} (${inst.name}, level ${inst.level}) for #${playerId}`);
  }
  inst.members.add(playerId);
  inst.emptySince = null;
  world.travel(playerId, inst.id, DUNGEON_ENTRY.x, DUNGEON_ENTRY.y);
  world.update(playerId, { 'dungeons:status': status(inst, playerId) });
  say(
    world,
    playerId,
    inst.cleared
      ? `You return to ${inst.name}.`
      : `You enter ${inst.name}. Somewhere below, ${inst.guardian} stirs.`,
  );
}

function leave(world: WorldAPI, playerId: number): void {
  const me = world.get(playerId);
  const inst = me ? instances.get(me.world ?? '') : undefined;
  if (!me || !inst) return;
  world.travel(playerId, OVERWORLD, inst.ex, inst.ey + 1);
  world.update(playerId, { 'dungeons:status': undefined });
}

/** Gear from any feature, picked by how much it is worth against the cave's level. */
function pickByValue(world: WorldAPI, tag: string, budget: number): ItemDef | undefined {
  const fitting = world
    .queryItemsByTag(tag)
    .filter((i) => (i.value ?? 0) > 0 && (i.value ?? 0) <= budget)
    .sort((a, b) => (b.value ?? 0) - (a.value ?? 0))
    .slice(0, 3);
  return fitting.length > 0 ? fitting[floor(world.rng() * fitting.length)] : undefined;
}

function openHoard(world: WorldAPI, playerId: number, args: unknown): void {
  const targetId = (args as { targetId?: unknown } | undefined)?.targetId;
  const me = world.get(playerId);
  const chest = typeof targetId === 'number' ? world.get(targetId) : undefined;
  const inst = me ? instances.get(me.world ?? '') : undefined;
  if (!me || !chest || !inst || chest.kind !== 'dungeons:chest' || cheb(me, chest) > 2) return;
  if (!inst.cleared) {
    say(world, playerId, `The hoard is sealed while ${inst.guardian} lives.`, 'bad');
    return;
  }
  if (inst.looted.has(playerId)) {
    say(world, playerId, 'You have already taken your share of this hoard.', 'info');
    return;
  }
  inst.looted.add(playerId);
  const level = inst.level;
  const gold = 15 * level + floor(world.rng() * 10 * level);
  const xp = 40 * level;
  const loot: ItemDef[] = [];
  const gear = pickByValue(world, 'equipment', 70 * level);
  if (gear && world.rng() < 0.85) loot.push(gear);
  const potion = pickByValue(world, 'potion', 25 * level);
  if (potion) loot.push(potion);
  const extras: [string, number][] = [
    ['dungeons:guardian_trophy', 1],
    ['dungeons:cave_crystal', 1 + floor(world.rng() * 3)],
  ];
  const names: string[] = [];
  const handOver = (itemId: string, count: number, name: string): void => {
    const left = world.give(playerId, itemId, count);
    if (left > 0) world.spawn('item', { x: me.x, y: me.y }, { itemDrop: { itemId, count: left } }, inst.id);
    names.push(count > 1 ? `${count} ${name}` : name);
  };
  for (const item of loot) handOver(item.id, 1, item.name);
  for (const [id, count] of extras) handOver(id, count, ITEMS.find((i) => i.id === id)?.name ?? id);
  world.emit('character:grant', {
    entityId: playerId,
    xp,
    gold,
    reason: `${inst.name} hoard · +${xp} XP · ${gold} gold · ${names.join(', ')}`,
    tone: 'loot',
  });
  world.update(playerId, { 'dungeons:status': status(inst, playerId) });
}

function onKilled(world: WorldAPI, payload: unknown): void {
  const ev = payload as { victimId?: unknown; killerId?: unknown; world?: unknown };
  if (typeof ev.victimId !== 'number' || typeof ev.world !== 'string') return;
  const inst = instances.get(ev.world);
  if (!inst || inst.cleared || ev.victimId !== inst.bossId) return;
  inst.cleared = true;
  for (const id of inst.own) {
    const e = world.get(id);
    if (e?.kind === 'dungeons:chest') {
      world.update(id, {
        label: 'Guardian’s hoard',
        'dungeons:hoard': { open: true },
        appearance: { frame: CHEST_OPEN, scale: 1.6 },
      });
    }
  }
  const killer = typeof ev.killerId === 'number' ? world.get(ev.killerId) : undefined;
  const by = (killer?.components.character as { name?: string } | undefined)?.name;
  for (const p of playersIn(world, inst.id)) {
    say(world, p.id, `${inst.guardian} has fallen${by ? ` to ${by}` : ''}! The hoard lies open.`);
  }
  refresh(world, inst);
}

function tick(world: WorldAPI): void {
  clock++;
  if (clock === 6) {
    for (const cave of world.query('dungeons:cave')) {
      const look = cave.components.appearance as { frame?: unknown } | undefined;
      if (look?.frame !== CAVE_MOUTH.frame) world.update(cave.id, { appearance: CAVE_MOUTH });
    }
  }
  if (clock === 5 && !world.getSet('dungeons:first-cave-v1')) {
    const x = WORLD_CENTER_X + FIRST_CAVE.dx;
    for (let y = WORLD_CENTER_Y + FIRST_CAVE.dy; y > WORLD_CENTER_Y + FIRST_CAVE.dy - 20; y--) {
      if (world.walkable(x, y) && world.queryNear(x, y, 1).length === 0) {
        spawnEntrance(world, x, y);
        world.getSet('dungeons:first-cave-v1', '1');
        break;
      }
    }
  }
  for (const inst of instances.values()) {
    if (inst.stage === 'ready') continue;
    prepare(world, inst);
    break;
  }
  if (clock % 10 !== 0) return;
  for (const inst of [...instances.values()]) {
    const inside = playersIn(world, inst.id);
    if (inside.length > 0) {
      inst.emptySince = null;
      if (inst.stage === 'ready' && inst.bossId === undefined && clock - inst.created > 50) {
        inst.cleared = true;
      }
      continue;
    }
    inst.emptySince ??= clock;
    if (clock - inst.emptySince < EMPTY_TICKS) continue;
    for (const e of world.queryNear(DUNGEON_SIZE >> 1, DUNGEON_SIZE >> 1, DUNGEON_SIZE, inst.id)) {
      world.despawn(e.id);
    }
    instances.delete(inst.id);
    world.log(`closed ${inst.id}`);
  }
  for (const p of world.query('dungeons:status')) {
    if (p.components['dungeons:status'] !== undefined && !isDungeonWorldId(p.world ?? OVERWORLD)) {
      world.update(p.id, { 'dungeons:status': undefined });
    }
  }
}

export default definePlugin({
  id: 'dungeons',
  items: ITEMS,
  recipes: [],
  entityKinds: ['dungeons:entrance', 'dungeons:exit', 'dungeons:chest', 'dungeons:sconce', 'dungeons:crystal'],
  systems: [{ name: 'dungeons:tick', fn: tick }],
  commands: [
    { name: 'dungeons:enter', fn: (world, args, id) => enter(world, id, args) },
    { name: 'dungeons:leave', fn: (world, _args, id) => leave(world, id) },
    { name: 'dungeons:open', fn: (world, args, id) => openHoard(world, id, args) },
  ],
  events: {
    'combat:killed': onKilled,
  },
  decorateChunk: (world, area, rng) => {
    if (rng() > CAVE_CHANCE) return;
    const midX = (area.minX + area.maxX) >> 1;
    const midY = (area.minY + area.maxY) >> 1;
    if (cheb({ x: midX, y: midY }, { x: WORLD_CENTER_X, y: WORLD_CENTER_Y }) < SAFE_RADIUS + 32) return;
    for (let attempt = 0; attempt < 40; attempt++) {
      const x = area.minX + 4 + floor(rng() * (area.maxX - area.minX - 8));
      const y = area.minY + 4 + floor(rng() * (area.maxY - area.minY - 8));
      const tile = world.tile(x, y);
      if (tile !== 'grass' && tile !== 'dirt' && tile !== 'forest') continue;
      if (!world.walkable(x, y) || !world.walkable(x, y + 1)) continue;
      const rocky = [world.tile(x, y - 1), world.tile(x - 1, y), world.tile(x + 1, y)].some((t) => t === 'mountain');
      if (!rocky && attempt < 30) continue;
      spawnEntrance(world, x, y);
      return;
    }
  },
});
